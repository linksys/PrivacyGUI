  /// Check if MAC is a locally administered (randomized) address.
  /// Returns true if the second hex digit is 2, 6, A, or E.
  static bool isRandomizedMac(String mac) {
    final cleaned = mac.toUpperCase().replaceAll(RegExp(r'[^0-9A-F]'), '');
    if (cleaned.length < 2) return false;
    final secondDigit = cleaned[1];
    return secondDigit == '2' ||
        secondDigit == '6' ||
        secondDigit == 'A' ||
        secondDigit == 'E';
  }

  /// Get a display-friendly vendor name or fallback.
  /// Returns "Private Address" for randomized MACs, null if unknown.
  static String? getVendorOrPrivate(String mac) {
    if (isRandomizedMac(mac)) return 'Private Address';
    return getVendor(mac);
  }
