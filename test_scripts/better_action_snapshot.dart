// Writes test/test_data/better_action_snapshot.json: the URL each JNAP action
// resolves to, for a set of service lists (#1923). better_action_snapshot_test.dart
// fails when the code resolves any of them differently.
//
// usage: dart test_scripts/better_action_snapshot.dart [routers.json]
//
// The inputs:
// - "seed": no service, so the lowest version of each action;
// - "baseline: …" and "pin: …": the services of the JNAP baseline and pin
//   that the app knows, from test/test_data/jnap_spec.json;
// - "all app services": every JNAPService;
// - "only: <service>": each JNAPService on its own;
// - "router: …": the services real routers report, copied from test/test_data/.
//   They are kept from the existing snapshot, or read from [routers.json]
//   (a map of name → services) when one is given.
//
// Run it only to change a mapping on purpose. Commit the result with the
// change, and list in the PR the actions whose URL changed.
import 'dart:convert';
import 'dart:io';

import 'package:privacy_gui/core/jnap/actions/better_action.dart';

const snapshotPath = 'test/test_data/better_action_snapshot.json';
const specPath = 'test/test_data/jnap_spec.json';

/// The name of the input that holds [service] on its own.
String onlyInput(String service) => 'only: $service';

/// The URL each action resolves to for a router that reports [services], or
/// null where it resolves to none. No service at all gives the seed.
///
/// It goes through what the app calls: initBetterActions, buildBetterActions
/// and JNAPAction.actionValue.
Map<String, String?> resolveActions(List<String> services) {
  if (services.isEmpty) {
    initBetterActions();
  } else {
    buildBetterActions(services);
  }
  return {
    for (final action in JNAPAction.values) action.name: _resolve(action)
  };
}

String? _resolve(JNAPAction action) {
  try {
    return action.actionValue;
  } on TypeError {
    // actionValue is `_betterActionMap[this]!`: an action with no URL throws.
    return null;
  }
}

Map<String, List<String>> _inputs(Map<String, List<String>> routers) {
  final spec = jsonDecode(File(specPath).readAsStringSync()) as Map;
  final appServices = JNAPService.values.map((s) => s.value).toList();
  final pinServices = (spec['services'] as Map).keys.toSet();
  final baselineServices = Set<String>.from(spec['baselineServices'] as List);
  final pin = (spec['pin'] as Map)['commit'] as String;
  final baseline = (spec['baseline'] as Map)['ref'] as String;

  return {
    'seed': [],
    'baseline: JNAP $baseline':
        appServices.where(baselineServices.contains).toList(),
    'pin: JNAP ${pin.substring(0, 7)}':
        appServices.where(pinServices.contains).toList(),
    'all app services': appServices,
    ...routers,
    for (final service in appServices) onlyInput(service): [service],
  };
}

void main(List<String> args) {
  final Map<String, List<String>> routers;
  if (args.isNotEmpty) {
    routers = (jsonDecode(File(args.first).readAsStringSync()) as Map).map(
        (name, services) =>
            MapEntry('$name', List<String>.from(services as List)));
  } else {
    final old = jsonDecode(File(snapshotPath).readAsStringSync()) as Map;
    routers = {
      for (final entry in (old['inputs'] as Map).entries)
        if ('${entry.key}'.startsWith('router: '))
          '${entry.key}': List<String>.from(entry.value as List),
    };
  }

  final inputs = _inputs(routers);
  final seed = resolveActions(const []);
  final results = <String, Map<String, String?>>{'seed': seed};
  for (final MapEntry(key: name, value: services) in inputs.entries) {
    if (name == 'seed') continue;
    final resolved = resolveActions(services);
    final changed = {
      for (final MapEntry(:key, :value) in resolved.entries)
        if (value != seed[key]) key: value,
    };
    if (changed.isNotEmpty) results[name] = changed;
  }

  const encoder = JsonEncoder.withIndent('  ');
  File(snapshotPath).writeAsStringSync('${encoder.convert({
        'about': 'Generated by test_scripts/better_action_snapshot.dart from '
            'the code as it was. "results.seed" maps every action; every '
            'other result lists only the actions that differ from the seed. '
            'null means the action resolves to no URL (#1923).',
        'inputs': inputs,
        'results': results,
      })}\n');
  stdout.writeln('wrote $snapshotPath: ${inputs.length} inputs');
}
