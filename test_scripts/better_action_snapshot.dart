// Writes test/test_data/better_action_snapshot.json: the URL each JNAP action
// resolves to, for a set of service lists (#1923). better_action_snapshot_test.dart
// fails when the code resolves any of them differently.
//
// usage: dart test_scripts/better_action_snapshot.dart [routers.json]
//
// The inputs:
// - "seed": no service, so the lowest version of each action;
// - "baseline: …" and "pin: …": the services of the JNAP baseline and pin
//   that the app knows, from test/test_data/jnap_spec.json;
// - "all app services": every JNAPService;
// - "only: <service>": each JNAPService on its own;
// - "router: …": the services real routers report, copied from test/test_data/.
//   They are kept from the existing snapshot. To add or replace them, pass
//   [routers.json], a map of name → services.
//
// Each input resolves from a fresh start (resolveActions).
//
// Run it only to change a mapping on purpose. Commit the result with the
// change, and list in the PR the actions whose URL changed.
import 'dart:convert';
import 'dart:io';

import '../test/core/jnap/actions/better_action_resolution.dart';

Map<String, List<String>> _routersFrom(String path, {required bool all}) {
  final json = jsonDecode(File(path).readAsStringSync()) as Map;
  final entries = all ? json : json['inputs'] as Map;
  return {
    for (final MapEntry(:key, :value) in entries.entries)
      if (all || '$key'.startsWith('router: '))
        '$key': List<String>.from(value as List),
  };
}

Future<void> main(List<String> args) async {
  final routers = args.isNotEmpty
      ? _routersFrom(args.first, all: true)
      : _routersFrom(snapshotPath, all: false);
  final spec = JnapSpec.load();

  final inputs = <String, List<String>>{
    'seed': [],
    'baseline: JNAP ${spec.baselineRef}': spec.appServicesAtBaseline,
    'pin: JNAP ${spec.pinCommit.substring(0, 7)}': spec.appServicesAtPin,
    'all app services': appServices,
    ...routers,
    for (final service in appServices) onlyInput(service): [service],
  };

  final resolved = await Future.wait(inputs.values.map(resolveActions));
  final seed = resolved.first;
  final results = <String, Map<String, String?>>{'seed': seed};
  for (final (index, name) in inputs.keys.indexed.skip(1)) {
    final changed = {
      for (final MapEntry(:key, :value) in resolved[index].entries)
        if (value != seed[key]) key: value,
    };
    if (changed.isNotEmpty) results[name] = changed;
  }

  const encoder = JsonEncoder.withIndent('  ');
  File(snapshotPath).writeAsStringSync('${encoder.convert({
        'about': 'Generated by test_scripts/better_action_snapshot.dart from '
            'the code as it was. Each input resolves from a fresh start. '
            '"results.seed" maps every action; every other result lists only '
            'the actions that differ from the seed. null means the action '
            'resolves to no URL (#1923).',
        'inputs': inputs,
        'results': results,
      })}\n');
  stdout.writeln('wrote $snapshotPath: ${inputs.length} inputs');
}
