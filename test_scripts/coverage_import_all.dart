// Writes the import-all helper that coverage needs (#1803 Q1).
//
// usage: dart test_scripts/coverage_import_all.dart
//
// `flutter test --coverage` lists only the files some test loads, so a file
// no test imports is missing from lcov.info, and the figure reads high. The
// helper imports every lib file a VM test can load, so each one is counted,
// at 0% when no test runs it.
//
// The helper is generated on each run, from the files that are there, so it
// cannot go stale. It is never committed: .gitignore lists it, and
// run_coverage.sh deletes it after the run.
//
// Left out:
// - lib/l10n/gen/, which is generated;
// - `part of` files, which their library brings in;
// - web-only files, which the VM cannot load.
import 'dart:io';

/// Where the helper goes. It ends in `_test.dart`, so the suite runs it.
const helperPath = 'test/import_all_for_coverage_test.dart';

/// The helper's one test. It passes once every import has loaded, which is
/// how coverage_summary.dart tells that the helper ran.
const helperTestName = 'imports every lib file, so coverage counts it';

/// An import that only a browser build can load: the list #1803 gives.
final _webOnlyImport = RegExp(
  r'''^import ['"](dart:html|dart:js|dart:ui_web|package:web/|package:js/|package:http/browser_client)''',
  multiLine: true,
);

final _partOf = RegExp(r'^part of', multiLine: true);

/// The helper's source, given each lib file's path and contents.
String importAllHelper(Map<String, String> libFiles) {
  final paths = [
    for (final MapEntry(key: path, value: source) in libFiles.entries)
      if (!path.startsWith('lib/l10n/gen/') &&
          !_partOf.hasMatch(source) &&
          !_webOnlyImport.hasMatch(source))
        path,
  ]..sort();
  return [
    '// Generated by test_scripts/coverage_import_all.dart for coverage',
    '// (#1803 Q1). Do not commit: it is rebuilt on each run.',
    '// ignore_for_file: unused_import',
    "import 'package:flutter_test/flutter_test.dart';",
    for (final (i, path) in paths.indexed)
      "import 'package:privacy_gui/${path.substring('lib/'.length)}' as i$i;",
    '',
    'void main() {',
    "  test('$helperTestName', () {});",
    '}',
    '',
  ].join('\n');
}

void main() {
  final libFiles = {
    for (final file in Directory('lib').listSync(recursive: true))
      if (file is File && file.path.endsWith('.dart'))
        file.path: file.readAsStringSync(),
  };
  File(helperPath).writeAsStringSync(importAllHelper(libFiles));
  stdout.writeln('Wrote $helperPath');
}
